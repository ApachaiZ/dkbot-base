//! Module `metrics` : export de métriques au format Prometheus TEXTFILE
//! (`<données>/metrics.prom`) pour un collecteur type node_exporter —
//! AUCUN port réseau ouvert (philosophie du projet : pas de surface).
//!
//! À chaque tick (60 s, désactivé à la volée via `/modules disable
//! metrics`) : une ligne par cible (CPU, RAM, disque, charge, uptime) et
//! par service (état systemd 0/1). Le fichier est réécrit en atomique
//! 0644 (lisible par le collecteur).

use std::sync::Arc;
use std::time::Duration;

use crate::api::Api;
use crate::embeds::state;
use crate::logger;
use crate::modules::MODULE_METRICS;
use crate::state::State;

const TICK: Duration = Duration::from_secs(60);

/// Boucle du module (tâche détachée, premier tick 30 s après Ready).
pub fn start(cfg: crate::config::Config, api: Arc<Api>, st: Arc<State>) {
    tokio::spawn(async move {
        tokio::time::sleep(Duration::from_secs(30)).await;
        let mut ticker = tokio::time::interval(TICK);
        loop {
            ticker.tick().await;
            if !st.module_enabled(MODULE_METRICS) {
                continue;
            }
            let mut out = String::from("# Generated by DakkaBot (module metrics)\n");
            out.push_str("# TYPE dakkabot_up gauge\ndakkabot_up 1\n");
            for target in &cfg.targets {
                collect_target(&cfg, &api, target.alias.as_str(), &mut out).await;
            }
            // Écriture ATOMIQUE 0644 : le collecteur ne lit jamais un
            // fichier tronqué ; lisible par node_exporter (autre user).
            let path = crate::paths::metrics_file();
            if let Some(parent) = path.parent() {
                let _ = std::fs::create_dir_all(parent);
            }
            let tmp = path.with_extension("prom.tmp");
            if std::fs::write(&tmp, out).is_ok() {
                use std::os::unix::fs::PermissionsExt;
                let _ = std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(0o644));
                let _ = std::fs::rename(&tmp, &path);
            }
        }
    });
}

async fn collect_target(
    cfg: &crate::config::Config,
    api: &Arc<Api>,
    target: &str,
    out: &mut String,
) {
    let mut errors: u32 = 0;
    let mut machine: Option<crate::status::Status> = None;
    for (alias, unit) in &cfg.services {
        match api.get(target, alias, false).await {
            Ok(status) => {
                let value = if state(&status) == "running" { 1 } else { 0 };
                out.push_str(&format!(
                    "dakkabot_service_state{{target=\"{target}\",service=\"{alias}\",unit=\"{unit}\"}} {value}\n"
                ));
                if machine.is_none() {
                    machine = Some(status);
                }
            }
            Err(_) => {
                errors += 1;
            }
        }
    }
    if let Some(status) = machine {
        let line =
            |name: &str, value: f64| format!("dakkabot_{name}{{target=\"{target}\"}} {value}\n");
        if let Some(cpu) = status.cpu_pct {
            out.push_str(&line("cpu_pct", cpu));
        }
        if let Some(ram) = status.ram_mb {
            out.push_str(&line("ram_mb", ram));
        }
        if let Some(disk) = status.disk_mb {
            out.push_str(&line("disk_mb", disk));
        }
        if let Some(load) = status.load1 {
            out.push_str(&line("load1", load));
        }
        if let Some(up) = status.uptime_seconds {
            out.push_str(&line("uptime_seconds", up));
        }
    } else {
        logger::warn(format!("metrics: target {target} unreachable"));
    }
    out.push_str(&format!(
        "dakkabot_collect_errors_total{{target=\"{target}\"}} {errors}\n"
    ));
}
